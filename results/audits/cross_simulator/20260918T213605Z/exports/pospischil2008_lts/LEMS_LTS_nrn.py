        self.display_caConcg.exec_menu("View = plot")
        self.display_ecab.exec_menu("View = plot")
        self.display_rates.exec_menu("View = plot")

        # ######################   File to save: time.dat (time). Note, saving in SI units
        py_v_time = [ t/1000 for t in h.v_time.to_python() ]  # Convert to Python list for speed...

        f_time_f2 = open('time.dat', 'w')
        num_points = len(py_v_time)  # Simulation may have been stopped before tstop...

        for i in range(num_points):
            f_time_f2.write('%f'% py_v_time[i])  # Save in SI units...
        f_time_f2.close()
        print("Saved data to: time.dat")

        # ######################   File to save: LTS.eca.dat (f_eca). Note, saving in SI units
        py_v_cai_f_eca = [ float(x  / 1000.0) for x in h.v_cai_f_eca.to_python() ]  # Convert to Python list for speed, variable has dim: voltage

        f_f_eca_f2 = open('LTS.eca.dat', 'w')
        num_points = len(py_v_time)  # Simulation may have been stopped before tstop...

        for i in range(num_points):
            f_f_eca_f2.write('%e\t%e\t\n' % (py_v_time[i], py_v_cai_f_eca[i], ))
        f_f_eca_f2.close()
        print("Saved data to: LTS.eca.dat")


import neuron

import time
import datetime
import sys

import hashlib
h = neuron.h
h.load_file("nrngui.hoc")

h("objref p")
h("p = new PythonObject()")

class NeuronSimulation():

    def __init__(self, tstop, dt=None, seed=123456789, abs_tol=None, rel_tol=None):

        print("\n    Starting simulation in NEURON of %sms generated from NeuroML2 model...\n"%tstop)

        self.setup_start = time.time()
        self.seed = seed
        self.abs_tol = abs_tol
        self.rel_tol = rel_tol
        import socket
        self.report_file = open('simulator.props','w')
        print('Simulator version:  %s'%h.nrnversion())
        self.report_file.write('# Report of running simulation with %s\n'%h.nrnversion())
        self.report_file.write('Simulator=NEURON\n')
        self.report_file.write('SimulatorVersion=%s\n'%h.nrnversion())

        self.report_file.write('SimulationFile=%s\n'%__file__)
        self.report_file.write('PythonVersion=%s\n'%sys.version.replace('\n',' '))
        print('Python version:     %s'%sys.version.replace('\n',' '))
        self.report_file.write('NeuroMLExportVersion=1.11.0\n')
        self.report_file.write('SimulationSeed=%s\n'%self.seed)
        self.report_file.write('Hostname=%s\n'%socket.gethostname())
        self.randoms = []
        self.next_global_id = 0  # Used in Random123 classes for elements using random(), etc. 

        self.next_spiking_input_id = 0  # Used in Random123 classes for elements using random(), etc. 

        '''
        Adding simulation Component(id=sim1 type=Simulation) of network/component: net (Type: networkWithTemperature:  temperature=308.15 (SI temperature))
        
        '''

        # Temperature used for network: 308.15 K
        h.celsius = 308.15 - 273.15

        # ######################   Population: pop0
        print("Population pop0 contains 1 instance(s) of component: cell of type: cell")

        h.load_file("cell.hoc")
        a_pop0 = []
        h("{ n_pop0 = 1 }")
        h("objectvar a_pop0[n_pop0]")
        for i in range(int(h.n_pop0)):
            h("a_pop0[%i] = new cell()"%i)
            h("access a_pop0[%i].soma"%i)

            self.next_global_id+=1

        h("{ a_pop0[0].position(0.0, 0.0, 0.0) }")

        h("proc initialiseV_pop0() { for i = 0, n_pop0-1 { a_pop0[i].set_initial_v() } }")
        h("objref fih_pop0")
        h('{fih_pop0 = new FInitializeHandler(0, "initialiseV_pop0()")}')

        h("proc initialiseIons_pop0() { for i = 0, n_pop0-1 { a_pop0[i].set_initial_ion_properties() } }")
        h("objref fih_ion_pop0")
        h('{fih_ion_pop0 = new FInitializeHandler(1, "initialiseIons_pop0()")}')

        print("Processing 2 input lists")

        # ######################   Input List: iclamp0
        # Adding single input: Component(id=0 type=input)
        h("objref iclamp0_0")
        h("a_pop0[0].soma { iclamp0_0 = new iclamp0(0.5) } ")

        # ######################   Input List: iclamp1
        # Adding single input: Component(id=0 type=input)
        h("objref iclamp1_0")
        h("a_pop0[0].soma { iclamp1_0 = new iclamp1(0.5) } ")

        print("Finished processing 2 input lists")

        trec = h.Vector()
        trec.record(h._ref_t)

        h.tstop = tstop

        if self.abs_tol is not None and self.rel_tol is not None:
            cvode = h.CVode()
            cvode.active(1)
            cvode.atol(self.abs_tol)
            cvode.rtol(self.rel_tol)
        else:
            h.dt = dt
            h.steps_per_ms = 1/h.dt

        # ######################   Display: self.display_
        self.display_ = h.Graph(0)
        self.display_.size(0,h.tstop,-80.0,50.0)
        self.display_.view(0, -80.0, h.tstop, 130.0, 80, 330, 330, 250)
        h.graphList[0].append(self.display_)
        # Line, plotting: pop0/0/cell/v
        self.display_.addexpr("a_pop0[0].soma.v(0.5)", "a_pop0[0].soma.v(0.5)", 1, 1, 0.8, 0.9, 2)

        # ######################   Display: self.display_d2
        self.display_d2 = h.Graph(0)
        self.display_d2.size(0,h.tstop,-80.0,50.0)
        self.display_d2.view(0, -80.0, h.tstop, 130.0, 80, 330, 330, 250)
        h.graphList[0].append(self.display_d2)
        # Line, plotting: pop0/0/cell/biophys/membraneProperties/ca_all/iDensity
        self.display_d2.addexpr("a_pop0[0].soma.i__ca_ca(0.5)", "a_pop0[0].soma.i__ca_ca(0.5)", 1, 1, 0.8, 0.9, 2)

        # ######################   Display: self.display_d3
        self.display_d3 = h.Graph(0)
        self.display_d3.size(0,h.tstop,-80.0,50.0)
        self.display_d3.view(0, -80.0, h.tstop, 130.0, 80, 330, 330, 250)
        h.graphList[0].append(self.display_d3)
        # Line, plotting: pop0/0/cell/caConc
        self.display_d3.addexpr("a_pop0[0].soma.cai(0.5)", "a_pop0[0].soma.cai(0.5)", 1, 1, 0.8, 0.9, 2)



        # ######################   File to save: time.dat (time)
        # Column: time
        h(' objectvar v_time ')
        h(' { v_time = new Vector() } ')
        h(' { v_time.record(&t) } ')
        if self.abs_tol is None or self.rel_tol is None:

            h.v_time.resize((h.tstop * h.steps_per_ms) + 1)

        # ######################   File to save: jlems_sccct.dat (outf)
        # Column: pop0/0/cell/v
        h(' objectvar v_v_outf ')
        h(' { v_v_outf = new Vector() } ')
        h(' { v_v_outf.record(&a_pop0[0].soma.v(0.5)) } ')
        if self.abs_tol is None or self.rel_tol is None:

            h.v_v_outf.resize((h.tstop * h.steps_per_ms) + 1)
        # Column: pop0/0/cell/caConc
        h(' objectvar v_ca_outf ')
        h(' { v_ca_outf = new Vector() } ')
        h(' { v_ca_outf.record(&a_pop0[0].soma.cai(0.5)) } ')
        if self.abs_tol is None or self.rel_tol is None:

            h.v_ca_outf.resize((h.tstop * h.steps_per_ms) + 1)
        # Column: pop0/0/cell/biophys/membraneProperties/ca_all/iDensity
        h(' objectvar v_ica_outf ')
        h(' { v_ica_outf = new Vector() } ')
        h(' { v_ica_outf.record(&a_pop0[0].soma.i__ca_ca(0.5)) } ')
        if self.abs_tol is None or self.rel_tol is None:

            h.v_ica_outf.resize((h.tstop * h.steps_per_ms) + 1)

        self.initialized = False

        self.sim_end = -1 # will be overwritten

        setup_end = time.time()
        self.setup_time = setup_end - self.setup_start
        print("Setting up the network to simulate took %f seconds"%(self.setup_time))

        h.nrncontrolmenu()


    def run(self):

        self.initialized = True
        sim_start = time.time()
        if self.abs_tol is not None and self.rel_tol is not None:
            print("Running a simulation of %sms (cvode abs_tol = %sms, rel_tol = %sms; seed=%s)" % (h.tstop, self.abs_tol, self.rel_tol, self.seed))
        else:
            print("Running a simulation of %sms (dt = %sms; seed=%s)" % (h.tstop, h.dt, self.seed))

        try:
            h.run()
        except Exception as e:
            print("Exception running NEURON: %s" % (e))
            return


        self.sim_end = time.time()
        self.sim_time = self.sim_end - sim_start
        print("Finished NEURON simulation in %f seconds (%f mins)..."%(self.sim_time, self.sim_time/60.0))

        try:
            self.save_results()
        except Exception as e:
            print("Exception saving results of NEURON simulation: %s" % (e))
            return


    def advance(self):

        if not self.initialized:
            h.finitialize()
            self.initialized = True

        h.fadvance()


    ###############################################################################
    # Hash function to use in generation of random value
    # This is copied from NetPyNE: https://github.com/Neurosim-lab/netpyne/blob/master/netpyne/simFuncs.py
    ###############################################################################
    def _id32 (self,obj): 
        return int(hashlib.md5(obj.encode('utf-8')).hexdigest()[0:8],16)  # convert 8 first chars of md5 hash in base 16 to int


    ###############################################################################
    # Initialize the stim randomizer
    # This is copied from NetPyNE: https://github.com/Neurosim-lab/netpyne/blob/master/netpyne/simFuncs.py
    ###############################################################################
    def _init_stim_randomizer(self,rand, stimType, gid, seed): 
        #print("INIT STIM  %s; %s; %s; %s"%(rand, stimType, gid, seed))
        rand.Random123(self._id32(stimType), gid, seed)


    def save_results(self):

        print("Saving results at t=%s..."%h.t)

        if self.sim_end < 0: self.sim_end = time.time()

        self.display_.exec_menu("View = plot")
        self.display_d2.exec_menu("View = plot")
        self.display_d3.exec_menu("View = plot")

        # ######################   File to save: time.dat (time). Note, saving in SI units
        py_v_time = [ t/1000 for t in h.v_time.to_python() ]  # Convert to Python list for speed...

        f_time_f2 = open('time.dat', 'w')
        num_points = len(py_v_time)  # Simulation may have been stopped before tstop...

        for i in range(num_points):
            f_time_f2.write('%f'% py_v_time[i])  # Save in SI units...
        f_time_f2.close()
        print("Saved data to: time.dat")

        # ######################   File to save: jlems_sccct.dat (outf). Note, saving in SI units
        py_v_v_outf = [ float(x  / 1000.0) for x in h.v_v_outf.to_python() ]  # Convert to Python list for speed, variable has dim: voltage
        py_v_ca_outf = [ float(x ) for x in h.v_ca_outf.to_python() ]  # Convert to Python list for speed, variable has dim: concentration
        py_v_ica_outf = [ float(x  / 0.1) for x in h.v_ica_outf.to_python() ]  # Convert to Python list for speed, variable has dim: currentDensity

        f_outf_f2 = open('jlems_sccct.dat', 'w')
        num_points = len(py_v_time)  # Simulation may have been stopped before tstop...

        for i in range(num_points):
            f_outf_f2.write('%e\t%e\t%e\t%e\t\n' % (py_v_time[i], py_v_v_outf[i], py_v_ca_outf[i], py_v_ica_outf[i], ))
        f_outf_f2.close()
        print("Saved data to: jlems_sccct.dat")

        save_end = time.time()
        save_time = save_end - self.sim_end
        print("Finished saving results in %f seconds"%(save_time))

        self.report_file.write('StartTime=%s\n'%datetime.datetime.fromtimestamp(self.setup_start).strftime('%Y-%m-%d %H:%M:%S'))
        self.report_file.write('SetupTime=%s\n'%self.setup_time)
        self.report_file.write('RealSimulationTime=%s\n'%self.sim_time)
        self.report_file.write('SimulationSaveTime=%s\n'%save_time)
        self.report_file.close()

        print("Saving report of simulation to %s"%('simulator.props'))

        print("Done")

if __name__ == '__main__':

    ns = NeuronSimulation(tstop=600, dt=0.001, seed=123456789, abs_tol=None, rel_tol=None)


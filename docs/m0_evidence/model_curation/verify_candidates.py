"""Verification stage for model-curation candidates (runs after ``curate_candidates.py fetch``).

For every candidate (and every screened-out model kept for evidence) this script records:

1. ``jnml -validate`` on the cell file (the NeuroSem structural oracle) and on the harness network.
2. A structural read of the cell XML: number of segments, channel densities and any element that
   is not a NeuroML core type (custom LEMS types break NeuroSem's mutation operators).
3. The shipped LEMS harness, copied to ``work/tmp/model-curation/runs/<model_id>/`` and run at its
   own time step and length, with spike times compared to the shipped OMV ``.mep`` reference
   when there is one (OMV engines use their own tolerances; here we only report the deviation).
   Only the pinned snapshot (fetched include closure) is copied, so a successful run also shows the
   closure is complete.
4. Whether the cell responds to injected current at all (an inclusion criterion of the spec).
5. A bracketing rheobase search and a short rheobase-scaled current-clamp battery generated by
   ``neurosem.protocols``. The derived numbers are *screening metrics* computed with simple
   NumPy rules, not NeuroSem eFEL features and not calibrated results; they only check whether
   the expected behaviour class (bursting, sag, rebound, adaptation) is plausibly present.
6. For cells with an Ih conductance (``channelDensity ion="h"``): an Ih-block control, i.e. the same
   hyperpolarising protocols at the same absolute currents on a work copy with that density set to 0.
   The control-minus-block difference is what attributes depolarising recovery (sag) to Ih; without
   it a recovery could come from any slow current.

Every record carries a ``run_id`` and ``code_state_id`` (SHA-256 of the core modules this script
calls, this script and the simulator version). Records from a different code state are never merged
into one file silently.

Outputs: ``verification.json`` and one figure per model under ``figures/``.
Usage: python docs/m0_evidence/model_curation/verify_candidates.py [--models ID ...] [--no-probes] [--drop-stale]
"""

